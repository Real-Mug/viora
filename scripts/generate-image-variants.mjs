/**
 * Generates responsive width variants for every photograph in /public/images.
 *
 * WHY THIS EXISTS
 * The static export has no image optimizer. The usual answer,
 * `images.unoptimized`, makes `next/image` emit a plain <img> with a single
 * `src` and no `srcset`, so every visitor downloads the full 1600px original
 * - about 1.3MB of photos on a property page - including a phone displaying
 * them 390px wide.
 *
 * This script pre-renders the sizes a browser would otherwise ask an optimizer
 * for. src/lib/image-loader.ts then maps each width next/image requests onto
 * the matching file, and next/image builds a real `srcset` from the result,
 * so the browser downloads the smallest file that fits its screen.
 *
 * WHAT IT WRITES
 *   public/images/**\/<name>-<width>w.webp   the variants (git-ignored)
 *   src/lib/data/image-manifest.json         src -> available widths (committed)
 *
 * Both the loader and this script must agree with `deviceSizes`/`imageSizes`
 * in next.config.ts. See WIDTHS below.
 *
 * The manifest is committed so `tsc --noEmit` and the dev server work on a
 * fresh clone; the image files are regenerated by `prebuild`/`predev` because
 * committing ~90 generated binaries is not worth the repository weight.
 *
 * Run directly with: node scripts/generate-image-variants.mjs
 */
import { readdir, mkdir, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, extname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const imagesDir = join(root, "public", "images");
const manifestPath = join(root, "src", "lib", "data", "image-manifest.json");

/**
 * Every width next/image can ask the loader for: `imageSizes` followed by
 * `deviceSizes` in next.config.ts. All of them must exist as real files,
 * because the `w` descriptor in a srcset states the file's actual pixel
 * width - pointing a "256w" entry at a 384px file makes the browser choose
 * badly. Keep this list and the two config arrays in step.
 */
const WIDTHS = [96, 176, 256, 384, 640, 828, 1200, 1600];

/** Photographs only. Brand marks and icons are never rendered by next/image. */
const SKIP_DIRS = new Set(["brand"]);
const RASTER = new Set([".webp", ".jpg", ".jpeg", ".png"]);

/** Matches a file this script itself produced, so runs are idempotent. */
const VARIANT = /-\d+w\.webp$/;

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      out.push(...(await walk(full)));
    } else if (RASTER.has(extname(entry.name).toLowerCase()) && !VARIANT.test(entry.name)) {
      out.push(full);
    }
  }
  return out;
}

async function main() {
  if (!existsSync(imagesDir)) {
    console.log("No public/images directory; nothing to do.");
    return;
  }

  const sources = await walk(imagesDir);
  const manifest = {};
  let written = 0;
  let skipped = 0;

  for (const file of sources) {
    const meta = await sharp(file).metadata();
    if (!meta.width) continue;

    const publicPath = "/" + relative(join(root, "public"), file).split(sep).join("/");
    const base = publicPath.replace(/\.[^.]+$/, "");

    // Only widths genuinely smaller than the source: upscaling adds bytes and
    // no detail. The original always serves as the largest candidate.
    const targets = WIDTHS.filter((w) => w < meta.width);
    const available = [...targets, meta.width];

    for (const width of targets) {
      const outPath = join(root, "public", `${base}-${width}w.webp`.slice(1));
      await mkdir(dirname(outPath), { recursive: true });

      // Skip work when the variant is already newer than its source.
      if (existsSync(outPath)) {
        const [a, b] = await Promise.all([stat(outPath), stat(file)]);
        if (a.mtimeMs >= b.mtimeMs) {
          skipped += 1;
          continue;
        }
      }

      await sharp(file).resize(width).webp({ quality: 78 }).toFile(outPath);
      written += 1;
    }

    manifest[publicPath] = { width: meta.width, height: meta.height ?? 0, widths: available };
  }

  await mkdir(dirname(manifestPath), { recursive: true });
  await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

  console.log(
    `Image variants: ${written} written, ${skipped} already current, ` +
      `${Object.keys(manifest).length} sources in manifest.`,
  );
}

await main();
